package com.recordlabs.desktop.platform

/** By Unicode block ranges (the scripts the app checks for). */
actual fun unicodeScriptOf(codePoint: Int): UScript = when (codePoint) {
    in 0x0041..0x005A, in 0x0061..0x007A, 0x00AA, 0x00BA, in 0x00C0..0x00D6, in 0x00D8..0x00F6,
    in 0x00F8..0x024F, in 0x1E00..0x1EFF, in 0x2C60..0x2C7F, in 0xA720..0xA7FF, in 0xFF21..0xFF3A, in 0xFF41..0xFF5A -> UScript.LATIN
    in 0x0300..0x036F, in 0x1AB0..0x1AFF, in 0x1DC0..0x1DFF, in 0x20D0..0x20FF, in 0xFE00..0xFE0F, in 0xFE20..0xFE2F, 0x3099, 0x309A -> UScript.INHERITED
    in 0x0370..0x03FF, in 0x1F00..0x1FFF -> UScript.GREEK
    in 0x0400..0x052F, in 0x2DE0..0x2DFF, in 0xA640..0xA69F, in 0x1C80..0x1C8F -> UScript.CYRILLIC
    in 0x0530..0x058F -> UScript.ARMENIAN
    in 0x0590..0x05FF, in 0xFB1D..0xFB4F -> UScript.HEBREW
    in 0x0600..0x06FF, in 0x0750..0x077F, in 0x08A0..0x08FF, in 0xFB50..0xFDFF, in 0xFE70..0xFEFF -> UScript.ARABIC
    in 0x0900..0x097F, in 0xA8E0..0xA8FF -> UScript.DEVANAGARI
    in 0x0E00..0x0E7F -> UScript.THAI
    in 0x0E80..0x0EFF -> UScript.LAO
    in 0x1000..0x109F, in 0xA9E0..0xA9FF, in 0xAA60..0xAA7F -> UScript.MYANMAR
    in 0x10A0..0x10FF, in 0x2D00..0x2D2F, in 0x1C90..0x1CBF -> UScript.GEORGIAN
    in 0x1780..0x17FF, in 0x19E0..0x19FF -> UScript.KHMER
    in 0x1100..0x11FF, in 0x3130..0x318F, in 0xA960..0xA97F, in 0xAC00..0xD7AF, in 0xD7B0..0xD7FF, in 0xFFA0..0xFFDC -> UScript.HANGUL
    in 0x3041..0x3096, in 0x309D..0x309F, in 0x1B001..0x1B11F -> UScript.HIRAGANA
    in 0x30A1..0x30FA, in 0x30FD..0x30FF, in 0x31F0..0x31FF, in 0x32D0..0x32FE, in 0x3300..0x3357, in 0xFF66..0xFF6F, in 0xFF71..0xFF9D -> UScript.KATAKANA
    in 0x2E80..0x2FDF, 0x3005, 0x3007, in 0x3021..0x3029, in 0x3038..0x303B, in 0x3400..0x4DBF, in 0x4E00..0x9FFF,
    in 0xF900..0xFAFF, in 0x20000..0x3134F -> UScript.HAN
    else -> UScript.COMMON
}

actual fun isLetterCodePoint(codePoint: Int): Boolean =
    if (codePoint < 0x10000) codePoint.toChar().isLetter()
    else unicodeScriptOf(codePoint).let { it != UScript.COMMON && it != UScript.INHERITED }
